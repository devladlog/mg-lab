"""DAX variables must not be named like DAX functions: Power BI rejects e.g. `VAR LastDate = ...` ("The syntax for
'LastDate' is incorrect") because LASTDATE is a function, and every query using that measure then fails with
"Failed to resolve name 'SYNTAXERROR'". Scans .tmdl, .dax and DAX blocks in .md/.yaml under the given folders."""
import re, sys, pathlib
FUNCS = set("""ABS ADDCOLUMNS ALL ALLEXCEPT ALLSELECTED AVERAGE AVERAGEX BLANK CALCULATE CALCULATETABLE CALENDAR
CALENDARAUTO CEILING CLOSINGBALANCEMONTH COALESCE CONCATENATE CONTAINS COUNT COUNTA COUNTBLANK COUNTROWS COUNTX
CROSSFILTER CURRENCY DATE DATEADD DATEDIFF DATESBETWEEN DATESINPERIOD DATESMTD DATESQTD DATESYTD DATEVALUE DAY
DISTINCT DISTINCTCOUNT DIVIDE EARLIER EDATE ENDOFMONTH ENDOFQUARTER ENDOFYEAR EOMONTH EXCEPT FILTER FILTERS FIND
FIRSTDATE FIRSTNONBLANK FIXED FLOOR FORMAT GENERATE GROUPBY HASONEVALUE HOUR IF INT INTERSECT ISBLANK ISERROR
ISFILTERED KEEPFILTERS LASTDATE LASTNONBLANK LEFT LEN LOOKUPVALUE LOWER MAX MAXX MEDIAN MID MIN MINUTE MINX MOD MONTH
NEXTDAY NEXTMONTH NEXTQUARTER NEXTYEAR NOT NOW OFFSET OR PARALLELPERIOD PATH PERCENTILE PREVIOUSDAY PREVIOUSMONTH
PREVIOUSQUARTER PREVIOUSYEAR QUARTER RANK RANKX RELATED RELATEDTABLE REMOVEFILTERS REPLACE RIGHT ROUND ROW
SAMEPERIODLASTYEAR SEARCH SECOND SELECTCOLUMNS SELECTEDVALUE STARTOFMONTH STARTOFQUARTER STARTOFYEAR SUBSTITUTE SUM
SUMMARIZE SUMMARIZECOLUMNS SUMX SWITCH TIME TODAY TOPN TOTALMTD TOTALQTD TOTALYTD TREATAS TRIM TRUE FALSE UNION UPPER
USERELATIONSHIP VALUE VALUES WEEKDAY WEEKNUM WINDOW YEAR YEARFRAC""".split())
bad = 0
for root in sys.argv[1:] or ["series"]:
    for p in pathlib.Path(root).rglob("*"):
        if p.suffix.lower() not in (".tmdl", ".dax", ".md", ".yaml", ".yml") or "node_modules" in p.parts:
            continue
        for i, line in enumerate(p.read_text(encoding="utf-8", errors="replace").splitlines(), 1):
            for m in re.finditer(r"\bVAR\s+([A-Za-z_][A-Za-z0-9_]*)\s*=", line):
                if m.group(1).upper() in FUNCS:
                    print(f"{p}:{i}: DAX variable '{m.group(1)}' is a DAX function name"); bad += 1
print(f"{bad} problem(s)")
sys.exit(1 if bad else 0)
