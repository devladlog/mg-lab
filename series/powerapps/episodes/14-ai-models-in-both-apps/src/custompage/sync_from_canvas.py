#!/usr/bin/env python3
"""Generate the model-driven custom page from the canvas files, so the formulas cannot drift between the two apps.

Src/App.pa.yaml  = canvas App.ai-formulas + App.ai-prompt formulas + the page's own two lines (ItemId, ThisInspectionItem)
Src/TriagePage.pa.yaml = canvas TriageScreen with selectedItem -> ThisInspectionItem and the screen renamed.
"""
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
CANVAS = HERE.parent / "app" / "Src"

HEADER = """# Custom page "Item AI triage" for the Inspection Back Office model-driven app (episode 12), opened by the command in ../commands.yaml with
#   Navigate(Self.Selected.Item, {Page: 'Item AI triage'})     which hands the record over as Param("id").
# GENERATED by sync_from_canvas.py from the canvas files: the formulas are the same text in both apps. Do not edit by hand.
"""


def formulas(path):
    return yaml.safe_load(path.read_text(encoding="utf-8"))["App"]["Properties"]["Formulas"].lstrip("=").rstrip().rstrip(";")


def render_app():
    parts = [formulas(CANVAS / "App.ai-formulas.pa.yaml"), formulas(CANVAS / "App.ai-prompt.pa.yaml"),
             'ItemId = GUID(Param("id"))', "ThisInspectionItem = LookUp('Inspection items', 'Inspection item' = ItemId)"]
    body = ";\n".join(parts) + ";"
    indented = "\n".join(("      " + l if l else "") for l in body.split("\n"))
    return HEADER + "App:\n  Properties:\n    Formulas: |-\n      =" + indented.lstrip() + "\n"


def render_screen():
    text = (CANVAS / "TriageScreen.pa.yaml").read_text(encoding="utf-8")
    body = text[text.index("Screens:"):]
    return HEADER + body.replace("selectedItem", "ThisInspectionItem").replace("TriageScreen:", "TriagePage:")


if __name__ == "__main__":
    (HERE / "Src" / "App.pa.yaml").write_text(render_app(), encoding="utf-8")
    (HERE / "Src" / "TriagePage.pa.yaml").write_text(render_screen(), encoding="utf-8")
