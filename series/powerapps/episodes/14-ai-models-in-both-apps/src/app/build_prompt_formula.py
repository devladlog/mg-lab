#!/usr/bin/env python3
"""Write Src/App.ai-prompt.pa.yaml: the system prompt as a Power Fx named formula, generated from ../prompts/system.md so the app cannot drift from it."""
from pathlib import Path

HERE = Path(__file__).resolve().parent


def formula(prompt):
    return '"' + prompt.strip().replace('"', '""') + '"'


def render(prompt):
    lines = formula(prompt).split("\n")
    body = "\n".join(("      " + l if l else "") if i else l for i, l in enumerate(lines))
    return ("# Generated by build_prompt_formula.py from src/prompts/system.md. Do not edit by hand.\n"
            "App:\n  Properties:\n    Formulas: |-\n      =TriageSystemPrompt = " + body + ";\n")


if __name__ == "__main__":
    (HERE / "Src" / "App.ai-prompt.pa.yaml").write_text(render((HERE.parent / "prompts" / "system.md").read_text(encoding="utf-8")), encoding="utf-8")
