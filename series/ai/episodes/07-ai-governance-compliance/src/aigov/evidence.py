"""Evidence pack: register + live Azure state -> findings per AI system, a report per system, and an exit code.

    PYTHONPATH=src python -m aigov.evidence --register governance/register.yaml \
        --subscription $SUB --resource-group rg-mglab-ai-07 [--save-snapshot reports/snapshot.json]
    PYTHONPATH=src python -m aigov.evidence --register governance/register.yaml --snapshot reports/snapshot.json

Exit code 0 = every applicable control passes; 1 = at least one FAIL (use it as a pipeline gate).
Reports are Markdown saved as .txt: Compliance Manager's Evidence tab accepts .txt but not .md.
"""
from __future__ import annotations

import argparse
import json
import sys
from dataclasses import asdict, dataclass, field
from datetime import date, datetime, timezone
from pathlib import Path

from . import controls, register
from .inventory import Account, Snapshot


@dataclass
class SystemResult:
    system_id: str
    name: str
    owner: str
    tier: str
    accounts: dict[str, list[controls.Finding]] = field(default_factory=dict)

    @property
    def failed(self) -> bool:
        return any(f.status == "FAIL" for fs in self.accounts.values() for f in fs)


def evaluate(systems: dict[str, register.System], snap: Snapshot, today: date):
    results: dict[str, SystemResult] = {}
    shadow: dict[str, controls.Finding] = {}
    for acc in snap.accounts:
        sys_ = systems.get(acc.system_id)
        if sys_ is None:
            shadow[acc.name] = controls.unregistered(acc)
            continue
        r = results.setdefault(sys_.id, SystemResult(sys_.id, sys_.name, sys_.owner, sys_.tier))
        r.accounts[acc.name] = controls.check_account(sys_, acc, today)
    not_found = sorted(set(systems) - set(results))
    return results, shadow, not_found


def render_console(results, shadow, not_found, snap: Snapshot) -> str:
    lines = [f"AI governance evidence  {snap.resource_group}  (state at {snap.taken_at})", ""]
    for r in results.values():
        lines.append(f"{r.system_id}  [{r.tier}]  owner: {r.owner}")
        for acc, findings in r.accounts.items():
            lines.append(f"  {acc}")
            for f in findings:
                lines.append(f"    {f.status:<4}  {f.control}  {f.title:<48} {f.evidence}")
        lines.append("")
    for name, f in shadow.items():
        lines.append(f"UNREGISTERED  {name}: {f.evidence}")
    for sid in not_found:
        lines.append(f"(info) {sid}: in the register, no resources in this resource group")
    total_fail = sum(r.failed for r in results.values()) + len(shadow)
    lines += ["", f"RESULT: {'FAIL' if total_fail else 'PASS'}  "
                  f"({len(results)} system(s) checked, {len(shadow)} unregistered resource(s))"]
    return "\n".join(lines)


def render_system_report(r: SystemResult, sys_: register.System, snap: Snapshot) -> str:
    verdict = "FAIL" if r.failed else "PASS"
    out = [f"# AI governance evidence: {sys_.name} ({sys_.id})", "",
           f"- Evidence taken (UTC): {snap.taken_at}",
           f"- Scope: subscription (masked), resource group `{snap.resource_group}`",
           f"- Accountable owner: {sys_.owner}",
           f"- Internal impact tier: {sys_.tier}",
           f"- Purpose: {sys_.purpose}",
           f"- Approved models: " + ", ".join(f"{m} {v}" for m, v in sys_.approved_models),
           f"- **Result: {verdict}**", ""]
    for acc, findings in r.accounts.items():
        out += [f"## Resource `{acc}`", "", "| Control | Requirement | Status | Evidence |", "|---|---|---|---|"]
        out += [f"| {f.control} | {f.title} | {f.status} | {f.evidence.replace('|', '/')} |" for f in findings]
        out.append("")
    out += ["## How this evidence was produced", "",
            "Generated by `aigov.evidence` from the AI register in the repository and read-only Azure Resource "
            "Manager calls (Cognitive Services accounts, deployments and guardrail policies, diagnostic settings, "
            "Azure Policy states). Process controls (owner, oversight, responsible-AI gate) are attested in the "
            "register and reviewed through pull requests.", ""]
    return "\n".join(out)


def main(argv=None) -> int:
    p = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    p.add_argument("--register", required=True)
    p.add_argument("--subscription")
    p.add_argument("--resource-group")
    p.add_argument("--snapshot", help="evaluate a saved snapshot instead of calling Azure")
    p.add_argument("--save-snapshot")
    p.add_argument("--out", default="reports")
    p.add_argument("--today", help="YYYY-MM-DD (default: today, UTC)")
    a = p.parse_args(argv)

    systems = register.load(a.register)
    if a.snapshot:
        snap = Snapshot.load(a.snapshot)
    else:
        if not (a.subscription and a.resource_group):
            p.error("--subscription and --resource-group are required without --snapshot")
        from azure.identity import DefaultAzureCredential

        from .arm import Arm
        from .inventory import collect
        snap = collect(Arm(DefaultAzureCredential()), a.subscription, a.resource_group)
    if a.save_snapshot:
        Path(a.save_snapshot).parent.mkdir(parents=True, exist_ok=True)
        snap.save(a.save_snapshot)

    today = date.fromisoformat(a.today) if a.today else datetime.now(timezone.utc).date()
    results, shadow, not_found = evaluate(systems, snap, today)
    print(render_console(results, shadow, not_found, snap))

    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)
    for r in results.values():
        (out / f"evidence-{r.system_id}.txt").write_text(render_system_report(r, systems[r.system_id], snap),
                                                         encoding="utf-8")
    (out / "evidence.json").write_text(json.dumps({
        "taken_at": snap.taken_at, "resource_group": snap.resource_group,
        "systems": {sid: {acc: [asdict(f) for f in fs] for acc, fs in r.accounts.items()}
                    for sid, r in results.items()},
        "unregistered": {n: asdict(f) for n, f in shadow.items()}, "not_found": not_found}, indent=2),
        encoding="utf-8")
    return 1 if (shadow or any(r.failed for r in results.values())) else 0


if __name__ == "__main__":
    sys.exit(main())
